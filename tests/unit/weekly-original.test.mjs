import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { installOriginal, saveOriginal, validateOriginal } from '../../scripts/weekly-original.mjs';

const date = '2026-11-23';
const bytes = Buffer.from('<!doctype html><html><head><title>周报 2026年11月23日</title></head><body><main><section>完整正文</section></main></body></html>');
const sha = b => createHash('sha256').update(b).digest('hex');
test('original is content addressed, read back, installed and safely resumed', () => {
  const root = mkdtempSync(join(tmpdir(), 'weekly-original-'));
  const source = join(root, 'input.html');
  writeFileSync(source, bytes);
  const args = { root, source, date, sha: sha(bytes) };
  const original = saveOriginal(args);
  assert.deepEqual(readFileSync(original), bytes);
  assert.equal(saveOriginal(args), original);
  const report = installOriginal(args);
  assert.deepEqual(readFileSync(report), bytes);
  assert.equal(installOriginal(args), report);
  writeFileSync(report, 'prior content');
  assert.throws(() => installOriginal(args), /Refusing to overwrite/);
  assert.equal(readFileSync(report, 'utf8'), 'prior content');
  const different = Buffer.concat([bytes, Buffer.from('\n')]);
  writeFileSync(source, different);
  assert.throws(() => saveOriginal({ ...args, sha: sha(different) }), /Refusing to overwrite/);
  assert.deepEqual(readFileSync(original), bytes);
});
test('missing or wrong explicit identity, truncation and malformed UTF-8 fail closed', () => {
  assert.throws(() => validateOriginal(bytes, date, ''));
  assert.throws(() => validateOriginal(bytes, '2026-02-30', sha(bytes)));
  assert.throws(() => validateOriginal(bytes, '2026-11-30', sha(bytes)), /title/);
  assert.throws(() => validateOriginal(bytes, date, '0'.repeat(64)), /SHA-256/);
  const empty = Buffer.from('<!doctype html><html><head><title>2026年11月23日</title></head><body><main></main></body></html>');
  assert.throws(() => validateOriginal(empty, date, sha(empty)), /sections/);
  const based = Buffer.from(bytes.toString().replace('<head>', '<head><base href="https://example.test/">'));
  assert.throws(() => validateOriginal(based, date, sha(based)), /base URL/);
  const quoted = Buffer.from(bytes.toString().replace('<head>', '<head><base title="A > B" href="/archive/">'));
  assert.throws(() => validateOriginal(quoted, date, sha(quoted)), /base URL/);
  const outside = Buffer.from('<!doctype html><html><head><title>2026年11月23日</title></head><body><header><section>outside</section></header><main></main></body></html>');
  assert.throws(() => validateOriginal(outside, date, sha(outside)), /sections/);
  const truncated = bytes.subarray(0, bytes.length - 7);
  assert.throws(() => validateOriginal(truncated, date, sha(truncated)), /Incomplete/);
  const bad = Buffer.concat([bytes, Buffer.from([0xff])]);
  assert.throws(() => validateOriginal(bad, date, sha(bad)));
  const root = mkdtempSync(join(tmpdir(), 'weekly-original-'));
  mkdirSync(join(root, 'reports'));
  assert.throws(() => installOriginal({ root, date, sha: sha(bytes) }));
});

test('normal builder rejects unarchived issue before touching generated pages and preserves conflicting history', () => {
  const root = mkdtempSync(join(tmpdir(), 'weekly-build-'));
  for (const dir of ['scripts', 'reports', 'weekly-reports']) mkdirSync(join(root, dir));
  for (const file of ['weekly-original.mjs', 'build-weekly-reports.mjs']) copyFileSync(new URL('../../scripts/' + file, import.meta.url), join(root, 'scripts', file));
  const source = join(root, 'input.html');
  writeFileSync(source, bytes);
  writeFileSync(join(root, 'reports', date + '.html'), bytes);
  writeFileSync(join(root, 'weekly-reports.html'), 'existing entry');
  const run = () => execFileSync(process.execPath, [join(root, 'scripts', 'build-weekly-reports.mjs')], { stdio: 'pipe' });
  assert.throws(run);
  assert.equal(readFileSync(join(root, 'weekly-reports.html'), 'utf8'), 'existing entry');
  saveOriginal({root, source, date, sha:sha(bytes)});
  run();
  const entry = readFileSync(join(root, 'weekly-reports.html'));
  const compat = join(root, 'weekly-reports', date + '.html');
  writeFileSync(compat, 'conflict');
  assert.throws(run);
  assert.deepEqual(readFileSync(join(root, 'weekly-reports.html')), entry);
  assert.equal(readFileSync(compat, 'utf8'), 'conflict');
});
